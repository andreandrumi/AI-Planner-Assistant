import { RegionProfile, YearMetrics, UrgencyLevel, SubPillars } from '../types';

export function computeUrgency(
  imdiComposite: number,
  subPillars: SubPillars,
  uniqueTalents: number,
  laborTarget: number,
  ipm: number,
  stagnant: boolean
): { urgencyScore: number; urgencyLevel: UrgencyLevel } {
  // Penetration ratio (0 to 1) based on real unique talents uploaded
  const talentRatio = laborTarget > 0 ? Math.min(uniqueTalents / laborTarget, 1.0) : 0;
  
  // Deficit scores (higher deficit -> higher urgency)
  const imdiDeficit = Math.max(0, (60 - imdiComposite) / 60) * 100;
  const talentDeficit = (1 - talentRatio) * 100;
  const empowermentDeficit = Math.max(0, (50 - subPillars.empowerment) / 50) * 100;
  const infraDeficit = Math.max(0, (50 - subPillars.infrastructure) / 50) * 100;
  const ipmDeficit = Math.max(0, (80 - ipm) / 80) * 100;

  let rawScore =
    imdiDeficit * 0.35 +
    talentDeficit * 0.25 +
    ((empowermentDeficit + infraDeficit) / 2) * 0.20 +
    ipmDeficit * 0.10 +
    (stagnant ? 10 : 0);

  const urgencyScore = Math.min(100, Math.max(10, Math.round(rawScore)));

  let urgencyLevel: UrgencyLevel = 'Telah Terpenuhi';
  if (urgencyScore >= 70) {
    urgencyLevel = 'Kritis';
  } else if (urgencyScore >= 45) {
    urgencyLevel = 'Perlu Perhatian';
  }

  return { urgencyScore, urgencyLevel };
}

// Clean initialization for Real Data: Starts at 0 training counts
// Real alumni data uploaded by user will populate actual metrics
export function createCleanYearlyData(
  baseImdi: number,
  baseSub: SubPillars,
  laborTarget: number,
  ipm: number
): Record<number, YearMetrics> {
  const result: Record<number, YearMetrics> = {};
  const years = [2022, 2023, 2024, 2025, 2026];

  for (let i = 0; i < years.length; i++) {
    const yr = years[i];
    // Baseline official IMDI scores
    const currentImdi = +(baseImdi + (i * 0.4)).toFixed(1);
    const currentSub: SubPillars = {
      infrastructure: +(baseSub.infrastructure + (i * 0.5)).toFixed(1),
      skills: +(baseSub.skills + (i * 0.4)).toFixed(1),
      empowerment: +(baseSub.empowerment + (i * 0.3)).toFixed(1),
      workforce: +(baseSub.workforce + (i * 0.3)).toFixed(1),
    };

    // ZERO DUMMY DATA: All training figures start at 0 until real data is uploaded
    const { urgencyScore, urgencyLevel } = computeUrgency(
      currentImdi,
      currentSub,
      0, // 0 real talents initially
      laborTarget,
      ipm,
      false
    );

    result[yr] = {
      year: yr,
      imdiComposite: currentImdi,
      subPillars: currentSub,
      totalAlumniRegistered: 0,
      uniqueTalents: 0,
      multiSkillCount: 0,
      segmentDistribution: { vokasi: 0, umkm: 0, asn: 0 },
      urgencyScore,
      urgencyLevel,
      stagnantWarning: false,
    };
  }

  return result;
}

